PINK = re.compile(r"rgba\((\d{2,3}),(\d{2,3}),(\d{2,3})")
HEX_PINK = re.compile(r"#([0-9a-f]{6}|[0-9a-f]{8})")


def pinkish(r, g, b):
    """Признак розового/сиреневого: красный выше зелёного, синий тоже высокий.

    Золото (240,207,146) под это не попадает: у него синий заметно ниже зелёного.
    """
    return r > g + 25 and b > g + 10 and b > 130 and r > 90


def main():
    check = "--check" in sys.argv
    raw = io.open(PATH, "rb").read()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8")
    before = text

    counts = {}

    # Сначала полные rgba() с новой прозрачностью — иначе замена троек уже
    # переписала бы их цвет и строки перестали бы совпадать.
    for old, new in ALPHAS:
        n = text.count(old)
        if n != 1:
            print("ВНИМАНИЕ: %-26s встречается %d раз" % (old, n))
            if n == 0:
                continue
        counts[old] = n
        text = text.replace(old, new)

    for old, new in TRIPLETS.items():
        n = text.count(old)
        if n:
            counts[old] = n
            text = text.replace(old, new)

    for old, new in HEX.items():
        n = text.count(old)
        if n:
            counts[old] = n
            text = text.replace(old, new)

    left = []
    for m in PINK.finditer(text):
        r, g, b = (int(m.group(i)) for i in (1, 2, 3))
        if pinkish(r, g, b):
            left.append(m.group(0))

    print("заменено разных образцов:", len(counts))
    print("осталось розовых rgba:", len(left), left[:8])
    if left:
        print("ПРОВАЛ: розовый остался.")
        return 1
    if check:
        print("--check: файл не изменён.")
        return 0
    if text == before:
        print("изменений нет.")
        return 0
    data = text.encode("utf-8")
    if crlf:
        data = data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
    io.open(PATH, "wb").write(data)
    print("записано:", PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
